package appeng.hooks.extensions;

import net.minecraft.core.BlockPos;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.LevelReader;

/**
 * Shim for NeoForge's {@code IItemExtension#doesSneakBypassUse}: whether blocks should still receive use interactions
 * while the player holding this item sneaks. The default body matches NeoForge's default.
 */
public interface SneakBypassUseHook {
    default boolean doesSneakBypassUse(ItemStack stack, LevelReader level, BlockPos pos, Player player) {
        return false;
    }
}
